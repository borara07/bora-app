/* ---------- 난도 정하기 (고치지 마세요) ----------
   배점으로 상·중·하를 정합니다. 위 설명의 규칙 그대로입니다.
   돌려주는 값: { 문항번호: "상" | "중" | "하" } */
function schoolLevels(exam) {
  var out = {};
  var qs = (exam && Array.isArray(exam.questions)) ? exam.questions : [];
  function isEssay(q) { return /^서답형/.test(String(q.form || '')) || /^서답형/.test(String(q.no)); }
  var objPoints = qs.filter(function (q) { return !isEssay(q); }).map(function (q) { return q.point; });
  var lo = objPoints.length ? Math.min.apply(null, objPoints) : 0;
  var hi = objPoints.length ? Math.max.apply(null, objPoints) : 0;
  qs.forEach(function (q) {
    var p = q.point;
    if (!objPoints.length || lo === hi) {
      out[q.no] = (isEssay(q) && objPoints.length) ? (p > hi ? '상' : p < lo ? '하' : '중') : '중';
    } else if (isEssay(q)) {
      out[q.no] = p > hi ? '상' : p < lo ? '하' : '중';
    } else {
      out[q.no] = p <= lo ? '하' : p >= hi ? '상' : '중';
    }
  });
  return out;
}
