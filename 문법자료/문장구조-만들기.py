"""13회·14회 [문장의 구조] 문제 만들기

자료: 내신대비 '문장의 짜임' (2020년 학교 기출 통합본)
방법: 문장을 주고 '둘 중 고르기' 로 깔고, 기출에서 온 5지선다를 얹습니다.
      원본의 밑줄은 괄호로 바꿨습니다.
      선생님 검토 결과에서 맞다고 본 고칠 점을 넣었습니다 (해설 끝 '고침' 표시).
      앞뒤에 두 번 실린 문항(창덕여고 묶음, 자운고 학습 활동)은 한 번만 넣었습니다.
      문장의 짜임과 상관없는 문항(높임법, 언어와 문화)과
      그림·표가 없으면 풀 수 없는 문항, 서술형은 넣지 않았습니다.
"""
import json, sys

R = {"13": [], "14": []}
CUR = None


def ox(kind, sent, yes, why):
    R[CUR].append({"kind": kind, "ask": "다음 설명이 맞으면 O, 틀리면 X",
                   "sentence": sent, "ox": True, "answer": 1 if yes else 2,
                   "explanation": why})


def two(kind, ask, sent, right, wrong, why, name=None):
    q = {"kind": kind, "ask": ask, "sentence": sent,
         "choices": [right, wrong], "answer": 1, "explanation": why}
    if name:
        q["name"] = name
    R[CUR].append(q)


def five(ask, choices, answer, why, name, sent=None, kind="종합객관식"):
    assert len(choices) == 5 and 1 <= answer <= 5, name
    # 해설이 보기 번호(①②…)를 가리키므로 보기 순서를 섞지 않습니다
    q = {"kind": kind, "ask": ask, "name": name, "choices": choices,
         "answer": answer, "explanation": why, "keepOrder": True}
    if sent:
        q["sentence"] = sent
    R[CUR].append(q)


