import json

A = []


def ox(kind, sent, yes, why, name=None):
    q = {"kind": kind, "ask": "다음 설명이 맞으면 O, 틀리면 X",
         "sentence": sent, "ox": True, "answer": 1 if yes else 2, "explanation": why}
    if name: q["name"] = name
    A.append(q)


def two(kind, ask, sent, right, wrong, why, name=None):
    q = {"kind": kind, "ask": ask, "sentence": sent,
         "choices": [right, wrong], "answer": 1, "explanation": why}
    if name: q["name"] = name
    A.append(q)


def five(kind, ask, choices, why, name, sent=None):
    q = {"kind": kind, "ask": ask, "name": name,
         "choices": choices, "answer": 1, "explanation": why}
    if sent: q["sentence"] = sent
    A.append(q)


