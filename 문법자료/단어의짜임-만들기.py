import json

Q = []


def ox(kind, sent, yes, why, name=None):
    q = {"kind": kind, "ask": "다음 설명이 맞으면 O, 틀리면 X",
         "sentence": sent, "ox": True, "answer": 1 if yes else 2,
         "explanation": why}
    if name:
        q["name"] = name
    Q.append(q)


def two(kind, ask, sent, right, wrong, why, name=None):
    q = {"kind": kind, "ask": ask, "sentence": sent,
         "choices": [right, wrong], "answer": 1, "explanation": why}
    if name:
        q["name"] = name
    Q.append(q)


def five(kind, ask, choices, answer, why, name, sent=None):
    q = {"kind": kind, "ask": ask, "name": name,
         "choices": choices, "answer": answer, "explanation": why}
    if sent:
        q["sentence"] = sent
    Q.append(q)


